#!/bin/sh
# Compile the bridge's compute shaders (kernel/ipu6-gpu/*.comp) to SPIR-V and embed them in
# kernel/ipu6-gpu/spirv.h, which is committed so builds without the NDK still work.
# Needs glslc (Android NDK: $ANDROID_NDK/shader-tools/linux-x86_64/glslc).
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
NDK=${ANDROID_NDK:-$HOME/Android/Sdk/ndk/27.3.13750724}
GLSLC=${GLSLC:-$NDK/shader-tools/linux-x86_64/glslc}
OUT=${1:-$ROOT/kernel/ipu6-gpu/spirv.h}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM
for s in grid box mix out; do
	"$GLSLC" -O --target-env=vulkan1.1 -I "$ROOT/kernel/ipu6-gpu" -o "$tmp/$s.spv" "$ROOT/kernel/ipu6-gpu/$s.comp"
done
python3 -I - "$tmp" "$OUT" <<'PY'
import struct, sys
tmp, out = sys.argv[1], sys.argv[2]
lines = ["/* Generated by tools/build_ipu6_gpu_shaders.sh from the shaders in kernel/ipu6-gpu; do not edit. */",
         "#include <stdint.h>"]
for name in ("grid", "box", "mix", "out"):
    data = open(f"{tmp}/{name}.spv", "rb").read()
    words = struct.unpack(f"<{len(data) // 4}I", data)
    lines.append(f"static const uint32_t spv_{name}[{len(words)}] = {{")
    for i in range(0, len(words), 8):
        lines.append("\t" + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
    lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
PY
echo "$OUT"
